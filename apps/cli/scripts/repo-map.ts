/**
 * `pnpm repo-map` writes docs/repo-map.md from the code itself, so a planning
 * session that can see only docs/ knows what actually exists. Every section is
 * derived from its source of truth in the tree, never from docs prose; one that
 * cannot be derived says "not derived: <reason>" instead of guessing.
 *
 * Deterministic on purpose: the header carries a commit date, never "now", and
 * every list is sorted, so two runs over the same tree write the same bytes.
 * The header's commit is HEAD, stepping back past commits that change only the
 * map, so committing the map alone ("chore: repo-map") does not make it stale.
 *
 * It reads only tracked and untracked-but-not-ignored files (`git ls-files`),
 * and it never opens a real .env: the env section reads files named
 * `.env*.example` and nothing else.
 *
 * It lives in apps/cli for that package's tsx and typescript, and deliberately
 * not behind the CLI entry, which loads dotenv (a real .env) and @aiugc/core.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript";

const OUT = "docs/repo-map.md";

const ROOT = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();

function git(args: string[]): string {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
}

const FILES = [
  ...new Set(git(["ls-files", "-z", "--cached", "--others", "--exclude-standard"]).split("\0")),
]
  .filter((f) => f && !f.endsWith("/") && existsSync(path.join(ROOT, f)))
  .sort();

const read = (file: string) => readFileSync(path.join(ROOT, file), "utf8");
const byText = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const code = (names: string[]) => names.map((name) => `\`${name}\``).join(", ");

function parse(file: string): ts.SourceFile {
  const kind = file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  return ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, false, kind);
}

function walk(node: ts.Node, visit: (node: ts.Node) => void): void {
  visit(node);
  ts.forEachChild(node, (child) => walk(child, visit));
}

/** A string literal, a plain template, or `"a" + "b"` — anything else is not static text. */
function stringValue(expr: ts.Expression | undefined): string | undefined {
  if (!expr) return undefined;
  if (ts.isStringLiteral(expr) || ts.isNoSubstitutionTemplateLiteral(expr)) return expr.text;
  if (ts.isBinaryExpression(expr) && expr.operatorToken.kind === ts.SyntaxKind.PlusToken) {
    const left = stringValue(expr.left);
    const right = stringValue(expr.right);
    return left !== undefined && right !== undefined ? left + right : undefined;
  }
  return undefined;
}

/** A section's expected failure to derive: printed as "not derived: <reason>". */
class NotDerived extends Error {}

function section(title: string, body: () => string[]): string[] {
  try {
    return [`## ${title}`, "", ...body(), ""];
  } catch (err) {
    if (!(err instanceof NotDerived)) throw err;
    return [`## ${title}`, "", `not derived: ${err.message}`, ""];
  }
}

/** One list entry: sorted by `key`, counted under `group` when the list is summarized. */
type Item = { key: string; group: string; line: string };

/**
 * The sorted list, or — past the section's line budget — counts per top-level
 * group, saying so. The budgets add up to keep the file under ~400 lines.
 */
function capped(items: Item[], budget: number, noun: string): string[] {
  if (items.length <= budget) {
    return items.sort((a, b) => byText(a.key, b.key) || byText(a.line, b.line)).map((i) => i.line);
  }
  const counts = new Map<string, number>();
  for (const { group } of items) counts.set(group, (counts.get(group) ?? 0) + 1);
  return [
    `${items.length} ${noun}: over this section's ${budget}-line budget, so summarized as counts per top-level group.`,
    "",
    ...[...counts.keys()].sort(byText).map((group) => `- \`${group}\` — ${counts.get(group)}`),
  ];
}

// --- header --------------------------------------------------------------------

function header(): string[] {
  let commit = "HEAD";
  while (git(["diff", "--name-only", `${commit}^`, commit, "--"]).trim() === OUT) commit += "^";
  const [sha, date] = git(["log", "-1", "--format=%H%n%cI", commit]).trim().split("\n");
  const branch = git(["branch", "--show-current"]).trim() || "(detached HEAD)";
  const dirty = git(["status", "--porcelain", "--", ".", `:(exclude)${OUT}`]).trim() !== "";
  return [
    "# Repo map",
    "",
    "Generated by `pnpm repo-map` (`apps/cli/scripts/repo-map.ts`) from the code itself. Do not edit by hand; rerun it.",
    "It lists what exists in the code, live or retired: whether something is retired is recorded in `docs/vault/`, not here.",
    "",
    `- Commit: \`${sha}\` (HEAD, skipping commits that change only this file)`,
    `- Branch: \`${branch}\``,
    `- Committed: ${date}`,
    ...(dirty
      ? [
          "- **The working tree had uncommitted changes: the lists below describe it, not the commit.**",
        ]
      : []),
    "",
  ];
}

// --- workspace packages ----------------------------------------------------------

function workspacePackages(): string[] {
  const globs: string[] = [];
  let inPackages = false;
  for (const line of read("pnpm-workspace.yaml").split(/\r?\n/)) {
    if (/^\S/.test(line)) inPackages = /^packages:\s*$/.test(line);
    else if (inPackages) {
      const match = /^\s+-\s+["']?([^"'#\s]+)/.exec(line);
      if (match) globs.push(match[1]!);
    }
  }
  if (globs.length === 0) throw new NotDerived("no `packages:` globs in pnpm-workspace.yaml");
  const manifests = globs.flatMap((glob) => {
    if (!/^[^*!]+(\/\*)?$/.test(glob)) {
      throw new NotDerived(`pnpm-workspace.yaml glob \`${glob}\` is not \`dir\` or \`dir/*\``);
    }
    const pattern = glob.endsWith("/*")
      ? new RegExp(`^${glob.slice(0, -2)}/[^/]+/package\\.json$`)
      : new RegExp(`^${glob}/package\\.json$`);
    return FILES.filter((file) => pattern.test(file));
  });
  // pnpm always counts the root as a workspace package, whatever the globs say.
  const items = ["package.json", ...manifests].map((file): Item => {
    const pkg = JSON.parse(read(file)) as { name?: string; description?: string };
    const dir = path.posix.dirname(file);
    const name = pkg.name ?? "(no name)";
    return {
      key: name,
      group: dir.split("/")[0]!,
      line: `- \`${name}\` — \`${dir}\` — ${pkg.description ?? "(no description in package.json)"}`,
    };
  });
  return [
    `The root package plus pnpm-workspace.yaml's ${code(globs)}, from each package.json:`,
    "",
    ...capped(items, 10, "packages"),
  ];
}

// --- Next.js routes --------------------------------------------------------------

const HTTP_METHODS = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"];

function exportedNames(sourceFile: ts.SourceFile): string[] {
  const names: string[] = [];
  for (const statement of sourceFile.statements) {
    const exported =
      ts.canHaveModifiers(statement) &&
      ts.getModifiers(statement)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (ts.isFunctionDeclaration(statement) && exported && statement.name) {
      names.push(statement.name.text);
    } else if (ts.isVariableStatement(statement) && exported) {
      for (const decl of statement.declarationList.declarations) {
        if (ts.isIdentifier(decl.name)) names.push(decl.name.text);
      }
    } else if (
      ts.isExportDeclaration(statement) &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) names.push(element.name.text);
    }
  }
  return names;
}

/** `/api/x/...` groups as `/api/x`; anything else by its first segment. */
function routeGroup(route: string): string {
  const segments = route.split("/").filter(Boolean);
  return "/" + segments.slice(0, segments[0] === "api" ? 2 : 1).join("/");
}

function nextRoutes(app: string, pageBudget: number, handlerBudget: number): string[] {
  // Next.js ignores src/app when a root app/ exists.
  const appDir = [`${app}/app/`, `${app}/src/app/`].find((dir) =>
    FILES.some((file) => file.startsWith(dir)),
  );
  if (!appDir) throw new NotDerived(`no \`${app}/app/\` or \`${app}/src/app/\` directory`);
  const pages: Item[] = [];
  const handlers: Item[] = [];
  for (const file of FILES) {
    if (!file.startsWith(appDir)) continue;
    const segments = file.slice(appDir.length).split("/");
    const kind = /^(page|route)\.[jt]sx?$/.exec(segments.pop()!)?.[1];
    if (!kind) continue;
    // Private `_x`, parallel `@x` and intercepting `(.)x` folders need routing rules
    // this does not implement — refuse rather than print a wrong path.
    const unsupported = segments.find((s) => /^(_|@|\(\.)/.test(s));
    if (unsupported) {
      throw new NotDerived(`\`${file}\` has a \`${unsupported}\` segment, which this does not map`);
    }
    // Route groups — `(marketing)` — organise files without adding a URL segment.
    const route = "/" + segments.filter((s) => !(s.startsWith("(") && s.endsWith(")"))).join("/");
    if (kind === "page") {
      pages.push({ key: route, group: routeGroup(route), line: `- \`${route}\`` });
    } else {
      const names = exportedNames(parse(file));
      const methods = HTTP_METHODS.filter((method) => names.includes(method));
      handlers.push({
        key: route,
        group: routeGroup(route),
        line: `- \`${route}\` — ${methods.length ? methods.join(", ") : "(no HTTP method exports found)"}`,
      });
    }
  }
  return [
    `From the \`page.*\` and \`route.*\` files under \`${appDir}\`; route groups \`(name)\` dropped from paths.`,
    "",
    `### Page routes (${pages.length})`,
    "",
    ...capped(pages, pageBudget, "page routes"),
    "",
    `### API routes: \`route.ts\` handlers, with their exported HTTP methods (${handlers.length})`,
    "",
    ...capped(handlers, handlerBudget, "route handlers"),
  ];
}

// --- database --------------------------------------------------------------------

const MIGRATIONS_DIR = "supabase/migrations/";
const SQL_NAME = `(?:"[^"]+"|[\\w$]+)(?:\\s*\\.\\s*(?:"[^"]+"|[\\w$]+))?`;

/** `"public"."jobs"` / `public.jobs` / `jobs` → `jobs`; other schemas keep their prefix. */
function tableName(raw: string): string {
  return raw.replace(/["\s]/g, "").replace(/^public\./, "");
}

function migrationFiles(): string[] {
  const files = FILES.filter(
    (file) =>
      file.startsWith(MIGRATIONS_DIR) && /^[^/]+\.sql$/.test(file.slice(MIGRATIONS_DIR.length)),
  );
  if (files.length === 0) throw new NotDerived(`no .sql files in ${MIGRATIONS_DIR}`);
  return files;
}

function migrations(): string[] {
  const files = migrationFiles();
  return [
    `${files.length} files in \`${MIGRATIONS_DIR}\`, in apply order:`,
    "",
    ...capped(
      files.map((file) => {
        const name = file.slice(MIGRATIONS_DIR.length);
        return { key: name, group: `${name.slice(0, 3)}x`, line: `- \`${name}\`` };
      }),
      60,
      "migrations",
    ),
  ];
}

/** Replays every CREATE / DROP / ALTER … RENAME TO table statement in migration order. */
function tables(): string[] {
  const live = new Map<string, string>();
  const dropped: string[] = [];
  const create = new RegExp(
    `\\bcreate\\s+(temp\\s+|temporary\\s+|unlogged\\s+)?table\\s+(?:if\\s+not\\s+exists\\s+)?(${SQL_NAME})`,
    "gi",
  );
  const rename = new RegExp(
    `\\balter\\s+table\\s+(?:if\\s+exists\\s+)?(?:only\\s+)?(${SQL_NAME})\\s+rename\\s+to\\s+(${SQL_NAME})`,
    "gi",
  );
  const drop = /\bdrop\s+table\s+(?:if\s+exists\s+)?([^;]+?)\s*(?:;|$)/gi;
  for (const file of migrationFiles()) {
    const id = path.posix.basename(file).split("_")[0]!;
    const sql = read(file)
      .replace(/\/\*[\s\S]*?\*\//g, " ")
      .replace(/--[^\n]*/g, " ");
    const ops: { at: number; apply: () => void }[] = [];
    for (const m of sql.matchAll(create)) {
      if (/^temp/i.test(m[1] ?? "")) continue;
      const name = tableName(m[2]!);
      ops.push({
        at: m.index!,
        apply: () => {
          if (!live.has(name)) live.set(name, id);
        },
      });
    }
    for (const m of sql.matchAll(rename)) {
      const [from, to] = [tableName(m[1]!), tableName(m[2]!)];
      ops.push({
        at: m.index!,
        apply: () => {
          const createdIn = live.get(from);
          if (createdIn === undefined) return;
          live.delete(from);
          live.set(to, createdIn);
        },
      });
    }
    for (const m of sql.matchAll(drop)) {
      const names = m[1]!.replace(/\s+(cascade|restrict)$/i, "").split(",");
      ops.push({
        at: m.index!,
        apply: () => {
          for (const name of names.map(tableName)) {
            if (live.delete(name)) dropped.push(`\`${name}\` in ${id}`);
          }
        },
      });
    }
    for (const op of ops.sort((a, b) => a.at - b.at)) op.apply();
  }

  const names = [...live.keys()].sort(byText);
  return [
    `${names.length} tables, replaying every \`CREATE TABLE\`, \`DROP TABLE\` and \`ALTER TABLE … RENAME TO\` in migration order (number = the migration that created it):`,
    "",
    ...capped(
      names.map((name) => ({
        key: name,
        group: live.get(name)!,
        line: `- \`${name}\` — ${live.get(name)}`,
      })),
      40,
      "tables",
    ),
    "",
    `Dropped along the way: ${dropped.length ? dropped.join(", ") : "none"}.`,
    "",
    drizzleCheck(names),
  ];
}

/** The code's own view of the tables, compared against the replay above. */
function drizzleCheck(migrationTables: string[]): string {
  const file = "packages/core/src/db/schema.ts";
  if (!FILES.includes(file)) return `Drizzle cross-check not derived: no ${file}.`;
  const declared: string[] = [];
  walk(parse(file), (node) => {
    if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      node.expression.text === "pgTable"
    ) {
      const name = stringValue(node.arguments[0]);
      if (name !== undefined) declared.push(name);
    }
  });
  const onlySchema = declared.filter((t) => !migrationTables.includes(t)).sort(byText);
  const onlyMigrations = migrationTables.filter((t) => !declared.includes(t));
  const list = (names: string[]) => (names.length ? code(names) : "none");
  return onlySchema.length || onlyMigrations.length
    ? `Drizzle cross-check (\`pgTable()\` in \`${file}\`, ${declared.length} declared) differs. Only in schema.ts: ${list(onlySchema)}. Only in the migrations: ${list(onlyMigrations)}.`
    : `Drizzle cross-check: the ${declared.length} \`pgTable()\` declarations in \`${file}\` are the same set.`;
}

// --- worker job types ------------------------------------------------------------

/** Parses only the files that mention `needle` — the core tree is large. */
function findInCore(needle: string, pick: (node: ts.Node) => ts.Node | undefined) {
  for (const file of FILES) {
    if (!/^packages\/core\/src\/.*\.ts$/.test(file) || !read(file).includes(needle)) continue;
    let found: ts.Node | undefined;
    walk(parse(file), (node) => (found ??= pick(node)));
    if (found) return { file, node: found };
  }
  return undefined;
}

function jobTypes(): string[] {
  const workerEntry = "apps/worker/src/index.ts";
  const runners = FILES.filter(
    (file) => /^apps\/[^/]+\/src\/.*\.tsx?$/.test(file) && read(file).includes("buildHandlers("),
  );
  if (!runners.includes(workerEntry)) {
    throw new NotDerived(`${workerEntry} does not call buildHandlers()`);
  }
  const registry = findInCore("function buildHandlers", (node) =>
    ts.isFunctionDeclaration(node) && node.name?.text === "buildHandlers" ? node : undefined,
  );
  if (!registry) throw new NotDerived("no `function buildHandlers` in packages/core/src");
  const types: string[] = [];
  walk(registry.node, (node) => {
    if (!ts.isReturnStatement(node) || !node.expression) return;
    if (!ts.isObjectLiteralExpression(node.expression)) return;
    for (const prop of node.expression.properties) {
      if (prop.name && (ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name))) {
        types.push(prop.name.text);
      }
    }
  });
  if (types.length === 0) {
    throw new NotDerived(`buildHandlers() in ${registry.file} returns no object literal`);
  }

  const heavyDecl = findInCore("HEAVY_JOB_TYPES", (node) =>
    ts.isVariableDeclaration(node) &&
    ts.isIdentifier(node.name) &&
    node.name.text === "HEAVY_JOB_TYPES"
      ? node
      : undefined,
  );
  const heavy: string[] = [];
  if (heavyDecl) {
    walk(heavyDecl.node, (node) => {
      if (ts.isStringLiteral(node)) heavy.push(node.text);
    });
  }
  const lane = (type: string) => (heavy.includes(type) ? "heavy" : "light");
  return [
    `The keys of \`buildHandlers()\` (\`${registry.file}\`), which ${code(runners)} run. ${
      heavyDecl
        ? `Lanes from \`HEAVY_JOB_TYPES\` (\`${heavyDecl.file}\`); every other type runs on the light lane.`
        : "Lanes not derived: no `HEAVY_JOB_TYPES` declaration in packages/core/src."
    }`,
    "",
    ...capped(
      types.map((type) => ({
        key: type,
        group: heavyDecl ? lane(type) : "all",
        line: `- \`${type}\`${heavyDecl ? ` — ${lane(type)} lane` : ""}`,
      })),
      20,
      "job types",
    ),
  ];
}

// --- CLI commands ----------------------------------------------------------------

type Cli = { parent: Cli | undefined; spec: string; description?: string };

function cliCommands(): string[] {
  const root: Cli = { parent: undefined, spec: "" };
  const commands = new Map<ts.Node, Cli>();

  for (const file of FILES.filter((f) => /^apps\/cli\/src\/.*\.ts$/.test(f))) {
    const sourceFile = parse(file);
    // Commander groups are top-level consts: `const qc = program.command("qc")`.
    const topLevel = new Map<string, ts.Expression>();
    for (const statement of sourceFile.statements) {
      if (!ts.isVariableStatement(statement)) continue;
      for (const decl of statement.declarationList.declarations) {
        if (ts.isIdentifier(decl.name) && decl.initializer) {
          topLevel.set(decl.name.text, decl.initializer);
        }
      }
    }
    // Which command an expression evaluates to. Every commander builder method
    // returns its receiver except `.command()`, which returns the new command.
    const commandOf = (expr: ts.Expression): Cli | undefined => {
      if (ts.isNewExpression(expr) && ts.isIdentifier(expr.expression)) {
        if (expr.expression.text !== "Command") return undefined;
        root.spec ||= stringValue(expr.arguments?.[0]) ?? "";
        return root;
      }
      if (ts.isIdentifier(expr)) {
        const init = topLevel.get(expr.text);
        return init ? commandOf(init) : undefined;
      }
      if (ts.isCallExpression(expr) && ts.isPropertyAccessExpression(expr.expression)) {
        if (expr.expression.name.text !== "command") return commandOf(expr.expression.expression);
        const known = commands.get(expr);
        if (known) return known;
        const spec = stringValue(expr.arguments[0]);
        const parent = commandOf(expr.expression.expression);
        if (spec === undefined || !parent) return undefined;
        const command: Cli = { parent, spec };
        commands.set(expr, command);
        return command;
      }
      return undefined;
    };
    walk(sourceFile, (node) => {
      if (!ts.isCallExpression(node) || !ts.isPropertyAccessExpression(node.expression)) return;
      const method = node.expression.name.text;
      if (method === "command") commandOf(node);
      if (method === "description") {
        const target = commandOf(node.expression.expression);
        if (target) {
          target.description =
            stringValue(node.arguments[0]) ?? "(not static text — read it in the source)";
        }
      }
    });
  }
  if (commands.size === 0) {
    throw new NotDerived("no commander `new Command()` / `.command()` calls in apps/cli/src");
  }

  const items = [...commands.values()].map((command): Item => {
    const names = [command.spec];
    for (let c = command.parent; c && c !== root; c = c.parent) {
      names.unshift(c.spec.split(" ")[0]!);
    }
    const name = names.join(" ");
    return {
      key: name,
      group: names[0]!.split(" ")[0]!,
      line: `- \`${name}\`${command.description ? ` — ${command.description}` : ""}`,
    };
  });
  return [
    `Commander definitions in \`apps/cli/src\` for the program \`${root.spec}\`${root.description ? ` ("${root.description}")` : ""}. Each group comes before its subcommands; options are not listed; no description means the source gives none.`,
    "",
    ...capped(items, 65, "commands"),
  ];
}

// --- Remotion compositions ---------------------------------------------------------

function compositions(): string[] {
  const items: Item[] = [];
  for (const file of FILES) {
    if (!/^packages\/remotion\/src\/.*\.tsx$/.test(file)) continue;
    walk(parse(file), (node) => {
      if (!ts.isJsxSelfClosingElement(node) && !ts.isJsxOpeningElement(node)) return;
      if (!ts.isIdentifier(node.tagName)) return;
      if (!["Composition", "Still"].includes(node.tagName.text)) return;
      for (const attr of node.attributes.properties) {
        if (!ts.isJsxAttribute(attr) || !ts.isIdentifier(attr.name) || attr.name.text !== "id") {
          continue;
        }
        const init = attr.initializer;
        const id =
          (init && ts.isStringLiteral(init)
            ? init.text
            : init && ts.isJsxExpression(init)
              ? stringValue(init.expression)
              : undefined) ?? "(non-literal id)";
        items.push({ key: id, group: file, line: `- \`${id}\` — \`${file}\`` });
      }
    });
  }
  if (items.length === 0) throw new NotDerived("no <Composition id=…> in packages/remotion/src");
  return [
    "`<Composition>` / `<Still>` ids in `packages/remotion/src`:",
    "",
    ...capped(items, 10, "compositions"),
  ];
}

// --- env var names -------------------------------------------------------------------

/** Names only, and only from `.env*.example` files — never a real .env. */
function envNames(): string[] {
  const examples = FILES.filter((file) => /(^|\/)\.env[^/]*\.example$/.test(file));
  if (examples.length === 0) throw new NotDerived("no .env*.example files in the tree");
  const lines = examples.map((file) => {
    const set = new Set<string>();
    const commented = new Set<string>();
    for (const line of read(file).split(/\r?\n/)) {
      const match = /^\s*(#\s*)?(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=/.exec(line);
      if (match) (match[1] ? commented : set).add(match[2]!);
    }
    const onlyCommented = [...commented].filter((name) => !set.has(name)).sort(byText);
    return `- \`${file}\` (${set.size}): ${code([...set].sort(byText))}${
      onlyCommented.length ? `; commented out: ${code(onlyCommented)}` : ""
    }`;
  });
  return [
    "Names declared in each `.env*.example` file (values never read). Only these files are read, so a name the code reads but no example declares is missing here.",
    "",
    ...lines,
  ];
}

